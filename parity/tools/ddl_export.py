#!/usr/bin/env python3
"""Generate Ecto tenant migrations from the Apache Fineract oracle's own schema and data.

E-CoreBank follows Fineract's data model (ADR-0001): same table names, columns, types, constraints
and indexes. Rather than retype 280 tables, this tool asks PostgreSQL for the definitions
(`pg_dump`) and wraps them in a migration. Because migrations are built module by module, a foreign
key to a table that does not exist yet is held back and added automatically by the migration that
creates the referenced table.

  ddl_export.py schema --app ecb_platform --name create_security_tables --version 20261114100000 \
                       --tables m_permission,m_role,m_role_permission
  ddl_export.py data   --app ecb_platform --name seed_permissions --version 20261114100100 \
                       --tables m_permission
  ddl_export.py status                      show what has been generated and which foreign keys wait

Needs the oracle's PostgreSQL running (parity/scripts/start-oracle.sh). The generated migrations go to
apps/<app>/priv/tenant_repo/migrations/. They are derived from Apache Fineract 1.16.1 (Apache
License 2.0) and are recorded in NOTICE. Standard library only.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

PARITY_DIR = Path(__file__).resolve().parent.parent
REPO = PARITY_DIR.parent
REGISTRY = PARITY_DIR / "inventory" / "schema-migrations.json"
DEFAULT_PORT = os.environ.get("PARITY_PG_PORT", "54330")
DB = "fineract_default"

HEADER = (
    "Derived from the database schema of Apache Fineract {version} (Apache License 2.0).\n"
    "Generated by parity/tools/ddl_export.py from the running oracle. Do not edit by hand:\n"
    "change the generator or the table list and regenerate."
)


def find_pg_dump() -> str:
    override = os.environ.get("PG_BIN")
    if override:
        for name in ("pg_dump.exe", "pg_dump"):
            if (Path(override) / name).exists():
                return str(Path(override) / name)
    found = shutil.which("pg_dump")
    if found:
        return found
    candidates = []
    for root in (r"D:\Program Files\PostgreSQL", r"C:\Program Files\PostgreSQL", "/usr/lib/postgresql"):
        base = Path(root)
        if base.is_dir():
            candidates += sorted(base.glob("*/bin/pg_dump*"))
    if candidates:
        return str(candidates[-1])
    sys.exit("error: pg_dump not found. Install PostgreSQL client tools or set PG_BIN.")


def fineract_version() -> str:
    groups = json.loads((PARITY_DIR / "inventory" / "groups.json").read_text(encoding="utf-8"))
    return re.search(r"openapi-(.+)\.json", groups["spec"]).group(1)


def run_pg_dump(args: list[str]) -> str:
    cmd = [find_pg_dump(), "-h", "127.0.0.1", "-p", DEFAULT_PORT, "-U", "postgres", "-d", DB, "--no-owner", "--no-privileges",
           "--no-comments", "--no-tablespaces", *args]
    proc = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8")
    if proc.returncode != 0:
        sys.exit(f"error: pg_dump failed: {proc.stderr.strip()}")
    return proc.stdout.replace("\r\n", "\n")


# --- parsing pg_dump output ---------------------------------------------------------------------


def split_statements(sql: str) -> list[str]:
    """Split on semicolons at the end of a line. pg_dump puts one statement per terminator."""
    statements, current = [], []
    for line in sql.split("\n"):
        stripped = line.strip()
        if not current and (stripped == "" or stripped.startswith("--")):
            continue
        current.append(line)
        if stripped.endswith(";"):
            statements.append("\n".join(current).strip())
            current = []
    if current:
        statements.append("\n".join(current).strip())
    return statements


NOISE = re.compile(r"^(SET |SELECT pg_catalog\.set_config|\\)", re.IGNORECASE)


def table_of(statement: str) -> str | None:
    m = re.match(r"(?:CREATE TABLE|ALTER TABLE(?: ONLY)?|CREATE (?:UNIQUE )?INDEX .* ON(?: ONLY)?)\s+(?:public\.)?\"?(\w+)\"?", statement, re.S)
    return m.group(1) if m else None


def fk_reference(statement: str) -> str | None:
    m = re.search(r"FOREIGN KEY .*? REFERENCES\s+(?:public\.)?\"?(\w+)\"?", statement, re.S)
    return m.group(1) if m else None


# --- registry -----------------------------------------------------------------------------------


def load_registry() -> dict:
    if REGISTRY.exists():
        return json.loads(REGISTRY.read_text(encoding="utf-8"))
    return {"migrations": [], "deferred_foreign_keys": []}


def save_registry(reg: dict) -> None:
    REGISTRY.write_text(json.dumps(reg, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")


def created_tables(reg: dict) -> set[str]:
    return {t for m in reg["migrations"] if m["kind"] == "schema" for t in m["tables"]}


# --- migration file -----------------------------------------------------------------------------


def module_name(app: str, name: str) -> str:
    prefix = "".join(part.capitalize() for part in app.split("_"))  # ecb_platform -> EcbPlatform
    prefix = prefix.replace("Ecb", "ECB", 1)
    return f"{prefix}.TenantRepo.Migrations.{''.join(p.capitalize() for p in name.split('_'))}"


def render_migration(app: str, name: str, version: str, ups: list[str], downs: list[str], note: str) -> str:
    lines = [f"defmodule {module_name(app, name)} do", '  @moduledoc """']
    lines += [f"  {line}" if line else "" for line in (HEADER.format(version=fineract_version()) + "\n\n" + note).split("\n")]
    lines += ['  """', "  use Ecto.Migration", "", "  def up do"]
    for sql in ups:
        lines += ['    execute(~S"""', *[f"    {l}" if l else "" for l in sql.split("\n")], '    """)', ""]
    lines += ["  end", "", "  def down do"]
    for sql in downs:
        lines += [f'    execute("{sql}")']
    lines += ["  end", "end", ""]
    return "\n".join(lines)


def write_migration(app: str, version: str, name: str, text: str) -> Path:
    directory = REPO / "apps" / app / "priv" / "tenant_repo" / "migrations"
    directory.mkdir(parents=True, exist_ok=True)
    # one file per (version, name): drop an older file for the same name so a re-run replaces it
    for old in directory.glob(f"*_{name}.exs"):
        old.unlink()
    path = directory / f"{version}_{name}.exs"
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


# --- commands -----------------------------------------------------------------------------------


def cmd_schema(args) -> int:
    tables = [t.strip() for t in args.tables.split(",") if t.strip()]
    reg = load_registry()
    existing = created_tables(reg) - {t for m in reg["migrations"] if m["name"] == args.name for t in m["tables"]}
    reg["migrations"] = [m for m in reg["migrations"] if m["name"] != args.name]
    reg["deferred_foreign_keys"] = [d for d in reg["deferred_foreign_keys"] if d["migration"] != args.name]
    available = existing | set(tables)

    flags = []
    for t in tables:
        flags += ["-t", f"public.{t}"]
    sql = run_pg_dump(["--schema-only", *flags])

    kept, deferred = [], []
    for st in split_statements(sql):
        if NOISE.match(st):
            continue
        ref = fk_reference(st)
        if ref and ref not in available:
            deferred.append({"table": table_of(st), "references": ref, "sql": st, "migration": args.name})
        else:
            kept.append(st)

    # foreign keys held back by earlier migrations whose target now exists
    late, still = [], []
    for d in reg["deferred_foreign_keys"]:
        (late if d["table"] in available and d["references"] in available else still).append(d)
    reg["deferred_foreign_keys"] = still + deferred

    missing = [t for t in tables if not any(re.search(rf"CREATE TABLE (?:public\.)?{t}\b", s) for s in kept)]
    if missing:
        sys.exit(f"error: not found in the oracle schema: {', '.join(missing)}")

    ups = kept + [d["sql"] for d in late]
    downs = [f"DROP TABLE IF EXISTS public.{t} CASCADE" for t in reversed(tables)]
    note = (
        f"Creates: {', '.join(tables)}.\n"
        + (f"Foreign keys added late (their tables now exist): {', '.join(sorted({d['table'] + ' -> ' + d['references'] for d in late}))}.\n" if late else "")
        + (f"Foreign keys held back until their tables exist: {', '.join(sorted({d['table'] + ' -> ' + d['references'] for d in deferred}))}.\n" if deferred else "")
    ).rstrip()
    path = write_migration(args.app, args.version, args.name, render_migration(args.app, args.name, args.version, ups, downs, note))

    reg["migrations"].append({"kind": "schema", "app": args.app, "version": args.version, "name": args.name, "tables": tables})
    reg["migrations"].sort(key=lambda m: m["version"])
    save_registry(reg)
    print(f"Wrote {path.relative_to(REPO)} ({len(kept)} statements, {len(late)} late foreign keys; {len(deferred)} held back)")
    return 0


def cmd_data(args) -> int:
    tables = [t.strip() for t in args.tables.split(",") if t.strip()]
    reg = load_registry()
    flags = []
    for t in tables:
        flags += ["-t", f"public.{t}"]
    sql = run_pg_dump(["--data-only", "--inserts", "--column-inserts", "--rows-per-insert=1", *flags])
    statements = [s for s in split_statements(sql) if not NOISE.match(s) and not s.upper().startswith("SELECT PG_CATALOG.SETVAL")]
    inserts = [s for s in statements if s.upper().startswith("INSERT INTO")]
    # keep identity and serial sequences ahead of the inserted ids
    resets = [
        f"SELECT setval(pg_get_serial_sequence('public.{t}', 'id'), COALESCE((SELECT MAX(id) FROM public.{t}), 1))"
        for t in tables if t_has_identity_id(t)
    ]
    # One statement per execute: PostgreSQL's extended protocol refuses several in one call, so the
    # inserts go in a single DO block.
    ups = ["DO $seed$\nBEGIN\n" + "\n".join(inserts) + "\nEND\n$seed$"] + resets
    downs = [f"DELETE FROM public.{t}" for t in reversed(tables)]
    note = f"Inserts the initial rows of: {', '.join(tables)} ({len(inserts)} rows)."
    path = write_migration(args.app, args.version, args.name, render_migration(args.app, args.name, args.version, ups, downs, note))
    reg["migrations"] = [m for m in reg["migrations"] if m["name"] != args.name]
    reg["migrations"].append({"kind": "data", "app": args.app, "version": args.version, "name": args.name, "tables": tables})
    reg["migrations"].sort(key=lambda m: m["version"])
    save_registry(reg)
    print(f"Wrote {path.relative_to(REPO)} ({len(inserts)} rows)")
    return 0


def t_has_identity_id(table: str) -> bool:
    sql = run_pg_dump(["--schema-only", "-t", f"public.{table}"])
    return bool(re.search(r"ALTER COLUMN id ADD GENERATED|\bid\b[^,\n]*(serial|nextval)", sql, re.IGNORECASE))


def cmd_status(_args) -> int:
    reg = load_registry()
    print(f"{len(reg['migrations'])} generated migration(s), {len(created_tables(reg))} tables created")
    for m in reg["migrations"]:
        print(f"  {m['version']} {m['app']:<14} {m['kind']:<6} {m['name']}: {', '.join(m['tables'])}")
    waiting = reg["deferred_foreign_keys"]
    print(f"{len(waiting)} foreign key(s) waiting for their tables:")
    for d in waiting:
        print(f"  {d['table']} -> {d['references']} (from {d['migration']})")
    return 0


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="command", required=True)
    for kind, func in (("schema", cmd_schema), ("data", cmd_data)):
        s = sub.add_parser(kind)
        s.add_argument("--app", required=True)
        s.add_argument("--name", required=True)
        s.add_argument("--version", required=True, help="Ecto migration version, for example 20261114100000")
        s.add_argument("--tables", required=True, help="comma-separated table names")
        s.set_defaults(func=func)
    sub.add_parser("status").set_defaults(func=cmd_status)
    args = p.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
