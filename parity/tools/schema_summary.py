#!/usr/bin/env python3
"""Summarise the exported Fineract schema by functional area and owning E-CoreBank app.

  schema_summary.py build   write parity/inventory/SCHEMA.md
  schema_summary.py check   fail if any table is not assigned to an area

Input: the CSV files written by parity/scripts/export-schema.sh and the rules in
parity/inventory/schema-areas.json. Standard library only. Python 3.9 or newer.
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

PARITY_DIR = Path(__file__).resolve().parent.parent
INVENTORY = PARITY_DIR / "inventory"
AREAS_FILE = INVENTORY / "schema-areas.json"


def version() -> str:
    spec = json.loads((INVENTORY / "groups.json").read_text(encoding="utf-8"))["spec"]
    return re.search(r"openapi-(.+)\.json", spec).group(1)


def load_rules():
    data = json.loads(AREAS_FILE.read_text(encoding="utf-8"))
    return [(re.compile(r["match"]), r["area"], r["app"]) for r in data["rules"]]


def assign(table: str, rules) -> tuple[str, str]:
    for pattern, area, app in rules:
        if pattern.search(table):
            return area, app
    return "unassigned", "?"


def load(ver: str):
    cols = INVENTORY / f"fineract-schema-{ver}-columns.csv"
    keys = INVENTORY / f"fineract-schema-{ver}-keys.csv"
    for p in (cols, keys):
        if not p.exists():
            sys.exit(f"error: {p} not found. Run parity/scripts/export-schema.sh with the oracle running")
    with cols.open(encoding="utf-8", newline="") as f:
        columns = list(csv.DictReader(f))
    with keys.open(encoding="utf-8", newline="") as f:
        constraints = list(csv.DictReader(f))
    return columns, constraints


def analyse(columns, constraints, rules):
    tables: dict[str, dict] = {}
    for c in columns:
        t = tables.setdefault(c["table_name"], {"columns": 0})
        t["columns"] += 1
    fks = defaultdict(int)
    for k in constraints:
        if k["type"] == "FOREIGN KEY":
            fks[k["table_name"]] += 1
    for name, t in tables.items():
        t["area"], t["app"] = assign(name, rules)
        t["fks"] = fks.get(name, 0)
    return tables


def cmd_check(_a) -> int:
    ver = version()
    columns, constraints = load(ver)
    tables = analyse(columns, constraints, load_rules())
    missing = sorted(n for n, t in tables.items() if t["area"] == "unassigned")
    if missing:
        print(f"{len(missing)} table(s) are not assigned to an area in schema-areas.json:")
        for n in missing:
            print(f"  - {n}")
        return 1
    print(f"OK: all {len(tables)} tables are assigned to an area")
    return 0


def cmd_build(_a) -> int:
    ver = version()
    columns, constraints = load(ver)
    tables = analyse(columns, constraints, load_rules())
    by_area: dict[tuple[str, str], list[str]] = defaultdict(list)
    for name, t in tables.items():
        by_area[(t["area"], t["app"])].append(name)

    lines = [
        f"# Fineract {ver} data model: tables by area",
        "",
        "Generated by `python parity/tools/schema_summary.py build` from the schema of the running Fineract",
        "oracle (`parity/scripts/export-schema.sh`). Do not edit by hand. This is the proven data model that",
        "E-CoreBank's schema follows (see [../../docs/design/00-fineract-design-reference.md](../../docs/design/00-fineract-design-reference.md)).",
        "",
        f"**{len(tables)} tables, {len(columns)} columns, {sum(1 for k in constraints if k['type'] == 'FOREIGN KEY')} foreign keys.**",
        "",
        "| Area | Owning app | Tables | Columns | Foreign keys |",
        "|---|---|---:|---:|---:|",
    ]
    for (area, app), names in sorted(by_area.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        lines.append(
            f"| {area} | {app} | {len(names)} | {sum(tables[n]['columns'] for n in names)} | {sum(tables[n]['fks'] for n in names)} |"
        )
    lines += ["", "## Tables per area", ""]
    for (area, app), names in sorted(by_area.items(), key=lambda kv: kv[0]):
        lines.append(f"### {area} ({app})")
        lines.append("")
        lines.append(", ".join(f"`{n}`" for n in sorted(names)))
        lines.append("")
    (INVENTORY / "SCHEMA.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    unassigned = len(by_area.get(("unassigned", "?"), []))
    print(f"Wrote {INVENTORY / 'SCHEMA.md'} ({len(tables)} tables, {unassigned} unassigned)")
    return 0


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="command", required=True)
    sub.add_parser("build").set_defaults(func=cmd_build)
    sub.add_parser("check").set_defaults(func=cmd_check)
    args = p.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
